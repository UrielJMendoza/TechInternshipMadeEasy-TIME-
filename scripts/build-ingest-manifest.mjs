import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
const root = new URL('../supabase/functions/ingest/', import.meta.url);
const files = (await readdir(root, { recursive: true })).filter(name => /\.(ts|json)$/.test(name) && !name.endsWith('.test.ts') && name !== 'manifest.ts').sort();
const hash = createHash('sha256');
for (const name of files) hash.update(name).update('\0').update(await readFile(new URL(name, root))).update('\0');
const checksum = hash.digest('hex');
await writeFile(new URL('manifest.ts', root), `// Generated by scripts/build-ingest-manifest.mjs\nexport const INGEST_SOURCE_CHECKSUM = ${JSON.stringify(checksum)};\n`);
console.log(checksum);
